  private DefaultTableModel tabelaDTM (List<filmes> lista){
        String[] coluna = {"ID", "Nome", "Data de Lançamento", "Categoria"};
        DefaultTableModel tabela = new DefaultTableModel(coluna, 0);

        
        for (filmes f : lista) {
    tabela.addRow(new Object[]{
        Integer.toString(f.getId()),
        f.getNome(),           
        filmes.converterParaJava(f.getDatalancamento()), 
        f.getCategoria()      
    });}
    
        return tabela;
  }
        
