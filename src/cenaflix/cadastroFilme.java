    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
    filmes f = new filmes();
    
    try{
        f.setNome(txtNomeFilme.getText());
        f.setDatalancamento(f.converterParaSQL(txtDataLancamento.getText()));
        f.setCategoria(txtCategoria.getText());
        if(filmeDAO.cadastrar(f)){
            JOptionPane.showMessageDialog(null, "Filme cadastrado com sucesso!");
        }
    }catch(Exception e){
        JOptionPane.showMessageDialog(null, "Não foi possível cadastrar o filme!");
    }
    }//GEN-LAST:event_btnCadastrarActionPerformed

